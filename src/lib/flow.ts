import 'server-only';
import { prisma } from './db';
import { extractInternalLinks, pathToSlug } from './links';

export type FlowLink = { path: string; label: string; adminHref: string; kind: 'page' | 'activity' | 'post' | 'arrangement' };

/**
 * Builds the site "flow": which page each section leads to, which pages link to a page,
 * and an ordering of pages that follows the website (Home → pages in the order Home links to them → …).
 */
export async function loadFlow() {
  const [pages, stays, activities, posts, arrangements, menus] = await Promise.all([
    prisma.page.findMany({ select: { id: true, slug: true, title: true, sections: { select: { id: true, type: true, data: true, draftData: true, order: true }, orderBy: { order: 'asc' } } } }),
    prisma.stay.findMany({ where: { published: true }, orderBy: { order: 'asc' }, select: { slug: true, pageSlug: true } }),
    prisma.activity.findMany({ select: { id: true, slug: true, title: true } }),
    prisma.post.findMany({ select: { id: true, slug: true, title: true } }),
    prisma.specialArrangement.findMany({ select: { id: true, slug: true, title: true } }),
    prisma.menu.findMany(),
  ]);
  const bySlug = new Map(pages.map((p) => [p.slug, p]));

  const resolve = (href: string): FlowLink | null => {
    const slug = pathToSlug(href);
    const page = bySlug.get(slug);
    if (page) return { path: `/${slug}`, label: page.title, adminHref: `/admin/pages/${page.id}`, kind: 'page' };
    const [first, second] = slug.split('/');
    if (first === 'experiences' && second) {
      const a = activities.find((x) => x.slug === second);
      if (a) return { path: `/${slug}`, label: a.title, adminHref: `/admin/collections/activities/${a.id}`, kind: 'activity' };
    }
    if (first === 'blog' && second) {
      const p = posts.find((x) => x.slug === second);
      if (p) return { path: `/${slug}`, label: p.title, adminHref: `/admin/collections/posts/${p.id}`, kind: 'post' };
    }
    if (first === 'special-arrangements' && second) {
      const s = arrangements.find((x) => x.slug === second);
      if (s) return { path: `/${slug}`, label: s.title, adminHref: `/admin/collections/specialArrangements/${s.id}`, kind: 'arrangement' };
    }
    return null;
  };

  /** Internal links of one section (buttons, cards, and pages generated by collection blocks). */
  const sectionLinks = (type: string, data: unknown): FlowLink[] => {
    const hrefs = extractInternalLinks(data);
    if (type === 'staysGrid') stays.forEach((s) => hrefs.push(`/${s.pageSlug || `stays/${s.slug}`}`));
    const seen = new Set<string>();
    return hrefs
      .map(resolve)
      .filter((l): l is FlowLink => !!l && !seen.has(l.adminHref) && !!seen.add(l.adminHref));
  };

  const pageLinks = new Map<string, FlowLink[]>(); // page slug → pages it links to (in order)
  for (const p of pages) pageLinks.set(p.slug, p.sections.flatMap((s) => sectionLinks(s.type, s.draftData || s.data)).filter((l) => l.kind === 'page'));

  const linkedFrom = (slug: string) =>
    pages
      .filter((p) => p.slug !== slug && (pageLinks.get(p.slug) || []).some((l) => l.path === `/${slug}`))
      .map((p) => ({ label: p.title, adminHref: `/admin/pages/${p.id}`, path: `/${p.slug}` }));

  // Site-flow ordering: BFS from Home following section links, then main-menu order, then the rest.
  const order: string[] = [];
  const queue = [''];
  while (queue.length) {
    const s = queue.shift()!;
    if (order.includes(s) || !bySlug.has(s)) continue;
    order.push(s);
    for (const l of pageLinks.get(s) || []) queue.push(pathToSlug(l.path));
  }
  const menuSlugs: string[] = [];
  const walk = (nodes: unknown) =>
    Array.isArray(nodes) &&
    nodes.forEach((n: { href?: string; children?: unknown }) => {
      if (n.href?.startsWith('/')) menuSlugs.push(pathToSlug(n.href));
      walk(n.children);
    });
  ['header', 'footer', 'utility', 'legal'].forEach((loc) => walk(menus.find((m) => m.location === loc)?.items));
  for (const s of menuSlugs) if (!order.includes(s) && bySlug.has(s)) order.push(s);
  for (const p of [...pages].sort((a, b) => a.slug.localeCompare(b.slug))) if (!order.includes(p.slug)) order.push(p.slug);

  return { pages, sectionLinks, linkedFrom, order, pageLinks };
}
